// Use stage4-fixtures.ts and a local production preview. Same external browser setup as stage4-browser.mjs.
import assert from 'node:assert/strict'
import { readFileSync, mkdirSync } from 'node:fs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright')
const save = readFileSync(process.env.COMPANY_SAVE ?? '/tmp/tycoon-stage4-company.json', 'utf8')
const shots = process.env.E2E_SHOTS ?? '/tmp/tycoon-stage4-actions-shots'
mkdirSync(shots, { recursive: true })
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
try {
  for (const width of [1280, 390, 320]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } })
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.addInitScript((save) => {
      localStorage.setItem('lab:tycoon:save', save)
      localStorage.setItem('lab:tycoon:muted', 'true')
    }, save)
    await page.goto(process.env.BASE_URL ?? 'http://127.0.0.1:4322/tycoon/')
    await page.locator('.scene-host canvas').waitFor()
    const pause = page.getByRole('button', { name: 'Pause', exact: true })
    await pause.click()
    const dismiss = page.getByRole('button', { name: 'Dismiss', exact: true })
    if (await dismiss.isVisible()) await dismiss.click()
    const ops = page.getByLabel('Company operations', { exact: true })
    const finite = ops.getByRole('combobox', { name: 'Finite initiative' })
    await finite.selectOption('grow:medium')
    assert.match(await ops.locator('.initiative-contract').innerText(), /Grow to Medium/)
    assert.match(await ops.locator('.initiative-contract').innerText(), /Upfront \$/)
    await ops.getByRole('button', { name: 'Assign initiative', exact: true }).click()
    assert.match(await ops.locator('.plan.build').innerText(), /Grow to Medium/)
    assert.equal(await pause.getAttribute('aria-pressed'), 'true', 'growth must preserve manual pause')
    await ops.getByRole('button', { name: 'Leave team idle', exact: true }).click()
    const reassign = page.getByRole('group', { name: 'Confirm reassignment' })
    assert.match(await reassign.innerText(), /all its progress/)
    await reassign.getByRole('button', { name: 'Confirm reassignment', exact: true }).click()
    await ops.locator('summary').filter({ hasText: 'Client & enterprise work' }).click()
    await ops.locator('.contract-offer').first().getByRole('button', { name: /Take it/ }).click()
    assert.match(await ops.locator('.plan.build').innerText(), /Client deadline/)
    assert.equal(await pause.getAttribute('aria-pressed'), 'true', 'client work must preserve manual pause')
    await ops.getByRole('button', { name: 'Abandon client work…', exact: true }).click()
    const abandon = page.getByRole('group', { name: 'Confirm contract abandonment' })
    assert.match(await abandon.innerText(), /deposit and loses .* reputation/)
    await abandon.getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.match(await ops.locator('.plan.build').innerText(), /Client deadline/)
    await ops.getByRole('button', { name: 'Abandon client work…', exact: true }).click()
    await abandon.getByRole('button', { name: 'Confirm abandonment', exact: true }).click()
    assert.equal(await ops.locator('.plan.build').count(), 0)
    const commercial = page.getByLabel('Product commercial controls')
    await commercial.locator('summary').click()
    await commercial.getByRole('button', { name: /Small ·/ }).click()
    assert.match(await commercial.innerText(), /Promoted for/)
    await commercial.getByRole('combobox', { name: 'Automatic promotion' }).selectOption('small')
    assert.equal(await pause.getAttribute('aria-pressed'), 'true')
    assert.ok(await commercial.getByRole('button', { name: 'License to other companies', exact: true }).isDisabled())
    assert.match(await commercial.innerText(), /Only a Flagship/)
    const context = ops.getByRole('combobox', { name: 'Product / ecosystem context' })
    const companionId = JSON.parse(save).products.find((p) => p.companionId === 'mobile_app').id
    await context.selectOption(String(companionId))
    await commercial.locator('summary').click()
    await commercial.getByRole('button', { name: /^(Sell product…|Retire product…)$/ }).click()
    const sunset = page.getByRole('group', { name: 'Confirm product sunset' })
    assert.match(await sunset.innerText(), /does not sell the company/)
    await sunset.getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.equal(await context.inputValue(), String(companionId))
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'page overflow')
    assert.ok(await commercial.evaluate((e) => e.scrollWidth <= e.clientWidth + 1), 'commercial overflow')
    assert.ok(await ops.evaluate((e) => e.scrollWidth <= e.clientWidth + 1), 'operations overflow')
    assert.equal(await page.locator('.modal').count(), 0)
    await commercial.scrollIntoViewIfNeeded()
    await page.waitForTimeout(1000)
    if (await dismiss.isVisible()) await dismiss.click()
    await page.screenshot({ path: `${shots}/commercial-${width}.png` })
    assert.deepEqual(errors, [])
    await page.close()
    console.log(`product actions acceptance passed at ${width}px`)
  }
} finally { await browser.close() }
