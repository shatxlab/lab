// CAPACITY_REVIEW=1 stage4-fixtures.ts -> /tmp/tycoon-stage4-capacity.json, then local production preview.
import assert from 'node:assert/strict'
import { readFileSync, mkdirSync } from 'node:fs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright')
const save = readFileSync(process.env.COMPANY_SAVE ?? '/tmp/tycoon-stage4-capacity.json', 'utf8')
const shots = process.env.E2E_SHOTS ?? '/tmp/tycoon-stage4-capacity-shots'
mkdirSync(shots, { recursive: true })
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
try {
  for (const width of [1280, 390, 320]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } }), errors = []
    page.on('pageerror', (e) => errors.push(e.message))
    await page.addInitScript((save) => { localStorage.setItem('lab:tycoon:save', save); localStorage.setItem('lab:tycoon:muted', 'true') }, save)
    await page.goto(process.env.BASE_URL ?? 'http://127.0.0.1:4322/tycoon/')
    await page.locator('.scene-host canvas').waitFor()
    const pause = page.getByRole('button', { name: 'Pause', exact: true })
    await pause.click()
    const dismiss = page.getByRole('button', { name: 'Dismiss', exact: true })
    if (await dismiss.isVisible()) await dismiss.click()
    const ops = page.getByLabel('Company operations', { exact: true }), health = page.getByRole('region', { name: 'Ecosystem health' })
    assert.match(await health.innerText(), /3 companions/)
    assert.match(await health.innerText(), /No fixed companion-count limit/)
    assert.match(await health.innerText(), /Shared care is over capacity/)
    const context = ops.getByRole('combobox', { name: 'Product / ecosystem context' })
    assert.match(await context.innerText(), /Retained ledger/)
    assert.match(await context.innerText(), /Retained planner/)
    await ops.getByRole('button', { name: 'reliability', exact: true }).click()
    const select = ops.getByRole('combobox', { name: 'Finite initiative' })
    await select.selectOption('item:companion:ai_assistant')
    const forecast = ops.getByLabel('Companion capacity forecast')
    assert.match(await forecast.innerText(), /0.00 provided/)
    assert.match(await forecast.innerText(), /0% coverage/)
    assert.match(await forecast.innerText(), /previous care output is excluded/)
    assert.match(await forecast.innerText(), /extra hosting \$/)
    assert.match(await ops.locator('.initiative-contract .warn').innerText(), /only 0%/)
    await ops.getByRole('button', { name: 'Assign initiative', exact: true }).click()
    const confirm = page.getByRole('group', { name: 'Confirm reassignment' })
    assert.match(await confirm.innerText(), /Stops reliability coverage immediately/)
    await confirm.getByRole('button', { name: 'Confirm reassignment', exact: true }).click()
    assert.match(await health.innerText(), /Pending launches: 1/)
    assert.match(await health.innerText(), /Shared reliability coverage: 0%/)
    assert.equal(await pause.getAttribute('aria-pressed'), 'true')
    assert.equal(await page.locator('.modal').count(), 0)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'page overflow')
    assert.ok(await health.evaluate((e) => e.scrollWidth <= e.clientWidth + 1), 'health overflow')
    assert.ok(await ops.evaluate((e) => e.scrollWidth <= e.clientWidth + 1), 'operations overflow')
    await health.scrollIntoViewIfNeeded()
    if (await dismiss.isVisible()) await dismiss.click()
    await page.screenshot({ path: `${shots}/capacity-${width}.png` })
    await page.getByRole('button', { name: 'Research', exact: true }).click()
    const research = page.locator('.modal')
    assert.match(await research.innerText(), /CI engineering practice/)
    assert.match(await research.innerText(), /QA automation practice/)
    assert.match(await research.innerText(), /standing reliability teams provide 10% more service output/)
    assert.ok(await research.evaluate((e) => e.scrollWidth <= e.clientWidth + 1), 'research overflow')
    await research.locator('.actions').getByRole('button', { name: 'Close', exact: true }).click()
    assert.deepEqual(errors, [])
    await page.close()
    console.log(`capacity and research acceptance passed at ${width}px`)
  }
} finally { await browser.close() }
